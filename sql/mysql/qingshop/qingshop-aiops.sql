SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `aiops_config` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `price_enabled` bit(1) NOT NULL DEFAULT b'1' COMMENT '智能定价是否启用（定时任务）',
  `price_mode` varchar(16) NOT NULL DEFAULT 'SUGGEST' COMMENT 'SUGGEST 建议待审批 / AUTO 自动执行',
  `floor_cost_ratio` decimal(6,3) NOT NULL DEFAULT 1.100 COMMENT '底价=成本价×该值',
  `floor_current_ratio` decimal(6,3) NOT NULL DEFAULT 0.700 COMMENT '底价=当前价×该值（两者取大）',
  `ceil_ratio` decimal(6,3) NOT NULL DEFAULT 1.300 COMMENT '顶价=当前价×该值',
  `max_change_ratio` decimal(6,3) NOT NULL DEFAULT 0.100 COMMENT '单次最大调整幅度',
  `cooldown_hours` int NOT NULL DEFAULT 72 COMMENT '同一 SKU 调价冷却（小时）',
  `stat_days` int NOT NULL DEFAULT 30 COMMENT '统计窗口（天）',
  `rule_refund_rate_hold` decimal(6,3) NOT NULL DEFAULT 0.300 COMMENT '退款率超过该值则不调价',
  `rule_zero_sales_days` int NOT NULL DEFAULT 7 COMMENT '零销量且上架天数≥该值 → 降价',
  `rule_zero_sales_cut_ratio` decimal(6,3) NOT NULL DEFAULT 0.080 COMMENT '零销量降价幅度（正数，实际为负）',
  `rule_hot_sales_min` int NOT NULL DEFAULT 3 COMMENT '畅销销量下限',
  `rule_hot_stock_days` int NOT NULL DEFAULT 7 COMMENT '畅销且库存天数低于该值 → 提价',
  `rule_hot_raise_ratio` decimal(6,3) NOT NULL DEFAULT 0.060 COMMENT '畅销提价幅度',
  `rule_conv_min` decimal(6,3) NOT NULL DEFAULT 0.100 COMMENT '转化率下限（订单/浏览）',
  `rule_conv_stock_days` int NOT NULL DEFAULT 30 COMMENT '高转化且库存天数高于该值 → 提价',
  `rule_conv_raise_ratio` decimal(6,3) NOT NULL DEFAULT 0.030 COMMENT '高转化提价幅度',
  `rule_new_product_days` int NOT NULL DEFAULT 7 COMMENT '新品观察期（上架不足该天数不调价）',
  `content_enabled` bit(1) NOT NULL DEFAULT b'0' COMMENT '内容优化是否启用（定时任务）',
  `content_mode` varchar(16) NOT NULL DEFAULT 'SUGGEST',
  `content_max_spu` int NOT NULL DEFAULT 5 COMMENT '每次最多处理的 SPU 数',
  `content_cooldown_hours` int NOT NULL DEFAULT 168,
  `llm_base_url` varchar(255) DEFAULT 'https://api.xiaomimimo.com/v1',
  `llm_model` varchar(64) DEFAULT 'mimo-v2.6-flash',
  `llm_key_env` varchar(64) DEFAULT 'LLM_SERVICE_KEY' COMMENT '存放 API Key 的环境变量名（Key 不入库）',
  `image_base_url` varchar(255) DEFAULT NULL COMMENT 'OpenAI 兼容图片接口，为空=未配置',
  `image_model` varchar(64) DEFAULT NULL,
  `image_key_env` varchar(64) DEFAULT NULL,
  `creator` varchar(64) DEFAULT '',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updater` varchar(64) DEFAULT '',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` bit(1) NOT NULL DEFAULT b'0',
  `tenant_id` bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_tenant` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI 运营配置';

CREATE TABLE IF NOT EXISTS `aiops_price_log` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `run_id` varchar(32) NOT NULL COMMENT '运行批次',
  `spu_id` bigint NOT NULL,
  `spu_name` varchar(255) DEFAULT NULL,
  `sku_id` bigint NOT NULL,
  `sku_name` varchar(255) DEFAULT NULL,
  `old_price` int NOT NULL COMMENT '原价（分）',
  `rule_price` int DEFAULT NULL COMMENT '规则建议价',
  `llm_price` int DEFAULT NULL COMMENT '大模型建议价（护栏前）',
  `new_price` int NOT NULL COMMENT '护栏后的最终价',
  `floor_price` int NOT NULL,
  `ceil_price` int NOT NULL,
  `cost_price` int DEFAULT NULL,
  `rule_reason` varchar(500) DEFAULT NULL,
  `reason` varchar(1000) DEFAULT NULL COMMENT '大模型理由',
  `guard_note` varchar(500) DEFAULT NULL COMMENT '护栏处理说明',
  `stats` text COMMENT '统计快照 JSON',
  `mode` varchar(16) NOT NULL,
  `status` tinyint NOT NULL DEFAULT 0 COMMENT '0 待审批 1 已执行 2 已拒绝 3 已回滚',
  `apply_time` datetime DEFAULT NULL,
  `rollback_time` datetime DEFAULT NULL,
  `creator` varchar(64) DEFAULT '',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updater` varchar(64) DEFAULT '',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` bit(1) NOT NULL DEFAULT b'0',
  `tenant_id` bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_sku_status` (`sku_id`, `status`),
  KEY `idx_spu` (`spu_id`),
  KEY `idx_run` (`run_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI 调价记录';

CREATE TABLE IF NOT EXISTS `aiops_content_log` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `run_id` varchar(32) NOT NULL,
  `spu_id` bigint NOT NULL,
  `old_name` varchar(255) DEFAULT NULL,
  `new_name` varchar(255) DEFAULT NULL,
  `old_introduction` varchar(512) DEFAULT NULL,
  `new_introduction` varchar(512) DEFAULT NULL,
  `old_keyword` varchar(512) DEFAULT NULL,
  `new_keyword` varchar(512) DEFAULT NULL,
  `old_description` longtext,
  `new_description` longtext,
  `selling_points` text COMMENT '卖点 JSON 数组',
  `image_prompts` text COMMENT '图片提示词 JSON 数组',
  `image_status` tinyint NOT NULL DEFAULT 0 COMMENT '0 无 1 待生成(未配置图片接口) 2 已生成 3 失败',
  `image_urls` text,
  `reason` varchar(1000) DEFAULT NULL,
  `stats` text,
  `mode` varchar(16) NOT NULL,
  `status` tinyint NOT NULL DEFAULT 0 COMMENT '0 待审批 1 已执行 2 已拒绝 3 已回滚',
  `apply_time` datetime DEFAULT NULL,
  `rollback_time` datetime DEFAULT NULL,
  `creator` varchar(64) DEFAULT '',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updater` varchar(64) DEFAULT '',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` bit(1) NOT NULL DEFAULT b'0',
  `tenant_id` bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_spu_status` (`spu_id`, `status`),
  KEY `idx_run` (`run_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI 商品内容改写记录';

